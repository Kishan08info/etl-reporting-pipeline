"""Reporting: read the marts, write the KPI report + charts.

Usage: python3 src/report.py
Writes: results/kpi_report.json, results/kpi_report.md,
        results/charts/mrr_trend.png, revenue_by_plan.png,
        churn_by_channel.png
"""
import json
import sqlite3
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "saas.sqlite"
OUT = ROOT / "results"
CHARTS = OUT / "charts"

plt.rcParams.update({"font.size": 10, "figure.dpi": 120})


def main():
    con = sqlite3.connect(DB)
    kpis = pd.read_sql("SELECT * FROM mart_monthly_kpis ORDER BY month", con)
    plan = pd.read_sql("SELECT * FROM mart_plan_monthly ORDER BY month, plan", con)
    channel = pd.read_sql("SELECT * FROM mart_churn_by_channel", con)
    top = pd.read_sql(
        "SELECT c.customer_id, ROUND(SUM(p.amount), 2) AS lifetime_revenue "
        "FROM dim_customers c JOIN dim_subscriptions s USING (customer_id) "
        "JOIN fact_payments p USING (subscription_id) "
        "GROUP BY c.customer_id ORDER BY lifetime_revenue DESC LIMIT 10", con)
    con.close()

    first, last = kpis.iloc[0], kpis.iloc[-1]
    total_revenue = float(kpis["revenue_collected"].sum())
    total_refunds = float(kpis["refunds"].sum())
    avg_churn = float(kpis["churn_rate_pct"].dropna().mean())
    avg_mom = float(kpis["mom_mrr_growth_pct"].dropna().mean())
    best_month = kpis.loc[kpis["revenue_collected"].idxmax()]
    worst_month = kpis.loc[kpis["revenue_collected"].idxmin()]

    report = {
        "period": f"{kpis['month'].iloc[0]} to {kpis['month'].iloc[-1]}",
        "n_months": len(kpis),
        "mrr_first_month": float(first["mrr"]),
        "mrr_last_month": float(last["mrr"]),
        "mrr_growth_pct": round(
            100 * (last["mrr"] - first["mrr"]) / first["mrr"], 1),
        "avg_mom_mrr_growth_pct": round(avg_mom, 2),
        "active_subs_first_month": int(first["active_subs"]),
        "active_subs_last_month": int(last["active_subs"]),
        "total_revenue_collected": round(total_revenue, 2),
        "total_refunds": round(total_refunds, 2),
        "avg_monthly_churn_rate_pct": round(avg_churn, 2),
        "best_revenue_month": {
            "month": str(best_month["month"]),
            "revenue": round(float(best_month["revenue_collected"]), 2),
        },
        "worst_revenue_month": {
            "month": str(worst_month["month"]),
            "revenue": round(float(worst_month["revenue_collected"]), 2),
        },
        "churn_by_channel": channel.to_dict("records"),
        "top_customer_lifetime_revenue": round(float(top["lifetime_revenue"].iloc[0]), 2),
        "top10_customers_share_pct": round(
            100 * top["lifetime_revenue"].sum() / total_revenue, 1),
        "revenue_by_plan_total": {
            row["plan"]: round(float(row["revenue"]), 2)
            for _, row in plan.groupby("plan")["revenue"].sum().reset_index().iterrows()
        },
    }
    (OUT / "kpi_report.json").write_text(json.dumps(report, indent=2))

    # ---- charts ---------------------------------------------------------
    CHARTS.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(9, 4.5))
    ax.plot(kpis["month"], kpis["mrr"], marker="o", label="MRR")
    ax.bar(kpis["month"], kpis["revenue_collected"], alpha=0.35,
           label="Revenue collected")
    ax.set_title("MRR and monthly revenue collected")
    ax.set_ylabel("USD")
    ax.legend()
    plt.xticks(rotation=45, ha="right")
    plt.tight_layout()
    fig.savefig(CHARTS / "mrr_trend.png")
    plt.close(fig)

    pivot = plan.pivot(index="month", columns="plan", values="revenue").fillna(0)
    fig, ax = plt.subplots(figsize=(9, 4.5))
    pivot.plot(kind="bar", stacked=True, ax=ax)
    ax.set_title("Monthly revenue by plan")
    ax.set_ylabel("USD")
    ax.legend(title="Plan")
    plt.xticks(rotation=45, ha="right")
    plt.tight_layout()
    fig.savefig(CHARTS / "revenue_by_plan.png")
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(channel["channel"], channel["churn_share_pct"])
    ax.set_title("Share of subscriptions churned, by acquisition channel")
    ax.set_ylabel("% of subscriptions churned")
    plt.xticks(rotation=20, ha="right")
    plt.tight_layout()
    fig.savefig(CHARTS / "churn_by_channel.png")
    plt.close(fig)

    md = f"""# SaaS Revenue Report — {report['period']}

Generated by `src/report.py` from the marts in `data/saas.sqlite`.

## Headline KPIs

| Metric | Value |
|---|---:|
| MRR, first month ({kpis['month'].iloc[0]}) | ${report['mrr_first_month']:,.2f} |
| MRR, last month ({kpis['month'].iloc[-1]}) | ${report['mrr_last_month']:,.2f} |
| MRR growth over period | {report['mrr_growth_pct']}% |
| Avg MoM MRR growth | {report['avg_mom_mrr_growth_pct']}% |
| Active subscriptions (first → last month) | {report['active_subs_first_month']} → {report['active_subs_last_month']} |
| Total revenue collected | ${report['total_revenue_collected']:,.2f} |
| Total refunds | ${report['total_refunds']:,.2f} |
| Avg monthly churn rate | {report['avg_monthly_churn_rate_pct']}% |
| Best revenue month | {report['best_revenue_month']['month']} (${report['best_revenue_month']['revenue']:,.2f}) |
| Worst revenue month | {report['worst_revenue_month']['month']} (${report['worst_revenue_month']['revenue']:,.2f}) |
| Top-10 customers' share of revenue | {report['top10_customers_share_pct']}% |

## Churn by acquisition channel

| Channel | Customers | Subscriptions | Churned | Churn share | Lifetime revenue |
|---|---:|---:|---:|---:|---:|
"""
    for _, r in channel.iterrows():
        md += (f"| {r['channel']} | {int(r['customers'])} | {int(r['subscriptions'])} | "
               f"{int(r['churned_subs'])} | {r['churn_share_pct']}% | "
               f"${r['lifetime_revenue']:,.2f} |\n")
    md += """
## Revenue by plan (whole period)

| Plan | Revenue |
|---|---:|
"""
    for p, v in report["revenue_by_plan_total"].items():
        md += f"| {p} | ${v:,.2f} |\n"
    md += """
## Charts

- `charts/mrr_trend.png` — MRR and revenue collected per month
- `charts/revenue_by_plan.png` — stacked monthly revenue by plan
- `charts/churn_by_channel.png` — churn share by acquisition channel
"""
    (OUT / "kpi_report.md").write_text(md)
    print(f"report written: {report['period']}, "
          f"MRR ${report['mrr_first_month']:,.0f} -> "
          f"${report['mrr_last_month']:,.0f} "
          f"(+{report['mrr_growth_pct']}%), "
          f"total revenue ${report['total_revenue_collected']:,.2f}")


if __name__ == "__main__":
    main()
